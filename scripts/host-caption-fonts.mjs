// One-off tool: downloads the caption fonts (SIL OFL 1.1) from Google Fonts into public/fonts/captions
// and writes src/features/captions/fonts-data.ts, so the app serves them itself (no third-party
// request, faster and private). Run again only when a font or a weight is added:
//   node scripts/host-caption-fonts.mjs
import { mkdir, writeFile } from "node:fs/promises";
import { basename } from "node:path";

const SUBSETS = ["latin", "latin-ext"];
// [font id, @remotion/google-fonts module, { style: weights }, subsets?]
const FONTS = [
  ["anton", "Anton", { normal: ["400"] }],
  ["bebas", "BebasNeue", { normal: ["400"] }],
  ["montserrat", "Montserrat", { italic: ["800", "900"], normal: ["500", "700", "800", "900"] }],
  ["playfair", "PlayfairDisplay", { normal: ["700", "900"], italic: ["400", "700", "900"] }],
  ["poppins", "Poppins", { normal: ["500", "600", "700", "800", "900"] }],
  ["instrument", "InstrumentSerif", { normal: ["400"], italic: ["400"] }],
  ["inter-tight", "InterTight", { normal: ["500", "600", "700", "800"] }],
  ["pinyon", "PinyonScript", { normal: ["400"] }],
  ["manrope", "Manrope", { normal: ["500", "600", "700"] }],
  ["bricolage", "BricolageGrotesque", { normal: ["600", "700", "800"] }],
  ["fraunces", "Fraunces", { italic: ["400", "600"], normal: ["600", "700"] }],
  ["syne", "Syne", { normal: ["600", "700", "800"] }],
  ["sora", "Sora", { normal: ["600", "700", "800"] }],
  ["dm-serif", "DMSerifDisplay", { italic: ["400"], normal: ["400"] }],
  ["outfit", "Outfit", { normal: ["500", "600", "700"] }],
  ["anybody", "Anybody", { normal: ["700", "800"] }],
  // Arabic letters of every style (variable font: one file for all the weights)
  ["cairo", "Cairo", { normal: ["500", "600", "700", "800", "900"] }, ["arabic"]],
  // Devanagari letters (Hindi, Marathi, Nepali) of every style
  [
    "noto-devanagari",
    "NotoSansDevanagari",
    { normal: ["500", "600", "700", "800", "900"] },
    ["devanagari"],
  ],
];

const outDir = new URL("../public/fonts/captions/", import.meta.url);
await mkdir(outDir, { recursive: true });

const downloaded = new Map();
async function fetchFile(url) {
  const name = `${basename(new URL(url).pathname)}`;
  if (!downloaded.has(url)) {
    const response = await fetch(url);
    if (!response.ok) throw new Error(`${response.status} ${url}`);
    await writeFile(new URL(name, outDir), Buffer.from(await response.arrayBuffer()));
    downloaded.set(url, name);
  }
  return downloaded.get(url);
}

const faces = [];
for (const [id, moduleName, styles, subsets = SUBSETS] of FONTS) {
  const info = (await import(`@remotion/google-fonts/${moduleName}`)).getInfo();
  for (const [style, weights] of Object.entries(styles)) {
    for (const weight of weights) {
      for (const subset of subsets) {
        const url = info.fonts[style]?.[weight]?.[subset];
        if (!url) continue;
        faces.push({
          id,
          family: info.fontFamily,
          style,
          weight,
          file: await fetchFile(url),
          unicodeRange: info.unicodeRanges[subset],
        });
      }
    }
  }
}

const source = `// Generated by scripts/host-caption-fonts.mjs: do not edit by hand.
export type FontFaceData = {
  id: string;
  family: string;
  style: "normal" | "italic";
  weight: string;
  file: string;
  unicodeRange: string;
};

export const FONT_FACES: FontFaceData[] = ${JSON.stringify(faces, null, 2)};
`;
await writeFile(new URL("../src/features/captions/fonts-data.ts", import.meta.url), source);
console.log(`${faces.length} faces, ${downloaded.size} files`);
